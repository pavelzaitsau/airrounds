#!/usr/bin/env python3
"""Vendor the shared protocol headers into the Flipper app so the catalog can build it.

The Flipper app and the ESP32 firmware share one protocol contract: a closure of headers
under firmware/esp32. The Flipper Apps Catalog builds only the `flipper/` subdirectory in
isolation, with no access to `../firmware`, so those headers must sit inside `flipper/`.

firmware/esp32 stays the single source of truth. This script copies the closure into
flipper/shared/, flattening the include paths and prefixing a banner, so the copy is clearly
generated. The host gate runs it with --check: it regenerates into memory and fails if the
committed copies diverge from the firmware originals.
"""

import argparse
import os
from pathlib import Path
import re
import shutil
import subprocess
import sys

ROOT = Path(__file__).resolve().parents[2]
FLIPPER = ROOT / "flipper"
SHARED = FLIPPER / "shared"
# The Flipper sources name the shared headers through shared/; each maps back to one firmware
# header, and the closure grows from there. Reading the shared/ includes keeps the seed list in
# step with the source automatically.
SHARED_INCLUDE = re.compile(r'^\s*#include "shared/([^"]+)"', re.MULTILINE)
QUOTED_INCLUDE = re.compile(r'^\s*#include "([^"<>]+)"', re.MULTILINE)
FIRMWARE = ROOT / "firmware/esp32"

BANNER = (
    "// Generated by tools/ci/vendor_flipper_shared.py. Do not edit.\n"
    "// Source of truth: {source}. The Flipper Apps Catalog builds flipper/ in\n"
    "// isolation, so this shared protocol header is vendored here with flattened\n"
    "// includes. The host gate (tools/quality/check.py) fails if this copy diverges.\n"
)


def seeds():
    names = set()
    for path in sorted(FLIPPER.glob("*.h")) + sorted(FLIPPER.glob("*.cpp")):
        for match in SHARED_INCLUDE.finditer(path.read_text()):
            names.add(match.group(1))
    if not names:
        raise SystemExit("No shared/ includes in flipper/; nothing to vendor")
    found = set()
    for name in sorted(names):
        matches = [path for path in FIRMWARE.rglob(name) if path.is_file()]
        if len(matches) != 1:
            raise SystemExit(f"Shared header {name!r} must match one firmware header, "
                             f"found {len(matches)}")
        found.add(matches[0].resolve())
    return found


def closure(seed_paths):
    """Return every firmware header reachable from the seeds through quoted includes."""
    pending = list(seed_paths)
    reached = {}
    while pending:
        path = pending.pop()
        if path in reached:
            continue
        if not path.is_file():
            raise SystemExit(f"Shared header is missing: {path}")
        text = path.read_text()
        reached[path] = text
        for match in QUOTED_INCLUDE.finditer(text):
            target = (path.parent / match.group(1)).resolve()
            if not target.is_relative_to(FIRMWARE.resolve()):
                raise SystemExit(f"{path.name} includes {match.group(1)} outside "
                                 f"{FIRMWARE.relative_to(ROOT).as_posix()}")
            if target not in reached:
                pending.append(target)
    names = [path.name for path in reached]
    if len(names) != len(set(names)):
        raise SystemExit(f"Two shared headers share a basename: {sorted(names)}")
    return reached


def clang_format(text, name):
    """Format a vendored header with flipper/.clang-format.

    The Flipper Apps Catalog builds flipper/ through `ufbt lint`, which formats every header
    in the bundle, flipper/shared/ included, so the vendored copies must already match that
    style or the catalog build fails. flipper/.clang-format sets SortIncludes: Never, so the
    flattened includes keep the order this script gives them.
    """
    binary = os.environ.get("CLANG_FORMAT") or shutil.which("clang-format")
    if not binary:
        raise SystemExit("clang-format not found; set CLANG_FORMAT or install clang-format")
    result = subprocess.run(
        [binary, "--style=file", f"--assume-filename={SHARED / name}"],
        input=text, capture_output=True, text=True,
    )
    if result.returncode != 0:
        raise SystemExit(f"clang-format failed on {name}: {result.stderr.strip()}")
    return result.stdout


def render(reached):
    """Return {basename: vendored text} with flattened includes, a banner and catalog formatting."""
    members = {path.resolve(): path.name for path in reached}
    rendered = {}
    for path, text in reached.items():
        def flatten(match):
            target = (path.parent / match.group(1)).resolve()
            if target in members:
                return f'#include "{members[target]}"'
            raise SystemExit(f"{path.name} includes {match.group(1)} outside the shared closure")
        body = QUOTED_INCLUDE.sub(flatten, text)
        rel = path.relative_to(ROOT).as_posix()
        rendered[path.name] = clang_format(BANNER.format(source=rel) + "\n" + body, path.name)
    return rendered


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true",
                        help="Fail if flipper/shared/ differs from a fresh vendoring")
    args = parser.parse_args()

    rendered = render(closure(seeds()))

    if args.check:
        stale = []
        committed = {path.name for path in SHARED.glob("*.h")} if SHARED.is_dir() else set()
        for name, text in rendered.items():
            current = SHARED / name
            if not current.is_file() or current.read_text() != text:
                stale.append(name)
        for extra in sorted(committed - set(rendered)):
            stale.append(f"{extra} (no longer shared)")
        if stale:
            raise SystemExit("flipper/shared/ is out of date; run "
                             "tools/ci/vendor_flipper_shared.py: " + ", ".join(sorted(stale)))
        print(f"flipper/shared/ matches firmware ({len(rendered)} headers)")
        return

    SHARED.mkdir(parents=True, exist_ok=True)
    for stale in SHARED.glob("*.h"):
        if stale.name not in rendered:
            stale.unlink()
    for name, text in rendered.items():
        (SHARED / name).write_text(text)
    print(f"Vendored {len(rendered)} shared headers into {SHARED.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
